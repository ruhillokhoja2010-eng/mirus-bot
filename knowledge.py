def entry_answer(entry, lang):
    return entry["ans"].get(lang) or entry["ans"][DEFAULT_LANG]

def find_answer(query, lang=DEFAULT_LANG, extra=(), threshold=85):
    """Возвращает (ответ, оценка) или (None, 0)."""
    q = norm(query)
    if len(q) < 2:
        return None, 0
    entries = list(ENTRIES) + list(extra)
    best_entry, best_score = None, 0
    for e in entries:
        for lg, keys in e["keys"].items():
            for k in keys:
                nk = norm(k)
                if nk == q:
                    return entry_answer(e, lang), 100
                score = fuzz.WRatio(q, nk)
                if len(nk) >= 6:
                    score = max(score, fuzz.token_set_ratio(q, nk))
                if score > best_score:
                    best_entry, best_score = e, score
